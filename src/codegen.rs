//! Генерация исходников потребителя из сохранённой схемы. rustc в БД не запускается.
use crate::{Kind, Result, Row, Schema};
use std::collections::HashSet;
use std::fmt::Write as _;
use std::path::Path;

fn rust_name(name: &str) -> String {
    match name {
        "self" | "Self" | "super" | "crate" => format!("r#{name}_"),
        "_" => "r#_field".into(),
        _ => format!("r#{name}"),
    }
}

fn struct_name(table: &str) -> String {
    let singular = table
        .strip_suffix('s')
        .filter(|s| !s.is_empty() && !s.ends_with(['s', 'u']))
        .unwrap_or(table);
    let mut result = String::new();
    for part in singular.split('_').filter(|p| !p.is_empty()) {
        let mut chars = part.chars();
        if let Some(c) = chars.next() {
            result.push(c.to_ascii_uppercase());
            result.extend(chars);
        }
    }
    if result.is_empty() {
        result.push_str("Record");
    }
    if result.starts_with(|c: char| c.is_ascii_digit()) {
        result.insert_str(0, "Table");
    }
    if result == "Self" {
        result.push_str("Record");
    }
    result
}

fn tag(kind: Kind) -> u8 {
    match kind {
        Kind::Null => 3,
        Kind::Int { .. } => 0,
        Kind::Float { .. } => 1,
        Kind::String { .. } => 2,
    }
}

// Лёгкая сверка метаданных; типовые ограничения схемы здесь не проверяем.
fn check_columns(
    schema: &Schema,
    table: &str,
    version: u32,
    columns: &[(&str, usize, u8)],
) -> Result<()> {
    if schema.name != table {
        return Err("Типизированный читатель получил другую таблицу".into());
    }
    if version == 0 || version > schema.version || columns.len() > schema.columns.len() {
        return Err("Потребитель собран под более новую VERSION: обновите базу или пересоберите потребителя".into());
    }
    let count = if schema.version == 1 && schema.columns_at_version.is_empty() {
        Some(schema.columns.len())
    } else {
        schema.columns_at_version.get(&version).copied()
    };
    if count != Some(columns.len()) {
        return Err("Число колонок не соответствует VERSION потребителя".into());
    }
    for ((name, width, kind), physical) in columns.iter().zip(&schema.columns) {
        if *name != physical.name
            || *width != physical.width()?
            || *kind != tag(physical.data_type.kind)
        {
            return Err("Несовместимая схема типизированного читателя".into());
        }
    }
    Ok(())
}

/// Полная проверка схемы перед циклом. Сгенерированный scan вызывает её один раз.
pub fn check_schema_once(
    schema: &Schema,
    table: &str,
    version: u32,
    columns: &[(&str, usize, u8)],
) -> Result<()> {
    schema.check()?;
    check_columns(schema, table, version, columns)
}

/// Постоянная по числу колонок проверка оболочки Row; поля проверяет Row::at.
/// Layout сегмента заранее проверяется при Table::open/create/add_column.
pub fn check_record(row: Row<'_>) -> Result<()> {
    if row.bytes.len() != row.layout.row_size
        || row.layout.cols.is_empty()
        || row.layout.cols.len() > row.schema.columns.len()
    {
        return Err("Неверный размер записи".into());
    }
    row.flag()?;
    Ok(())
}

/// Обычный from_row сверяет имена/типы/ширины; ограничений схемы в цикле нет.
pub fn check_reader(
    row: Row<'_>,
    table: &str,
    version: u32,
    columns: &[(&str, usize, u8)],
) -> Result<()> {
    check_columns(row.schema, table, version, columns)?;
    check_record(row)
}

/// Генерирует один тип, возвращая ошибки схемы обычным Result.
/// Для VALIDATOR потребитель определяет `fn validate(&self) -> minidb::Result<()>`
/// в собственном impl; сгенерированный адаптер вызывает этот метод.
pub fn generate(schema: &Schema) -> Result<String> {
    schema.check()?;
    if let Some(col) = schema
        .columns
        .iter()
        .find(|c| matches!(c.data_type.kind, Kind::Null))
    {
        return Err(format!(
            "Тип {}.{} ещё NULL: сначала запишите ненулевое значение, затем сгенерируйте Rust-код",
            schema.name, col.name
        )
        .into());
    }
    let layout = crate::layout::Layout::from_schema(schema)?;
    let name = struct_name(&schema.name);
    let mut names = HashSet::new();
    for col in &schema.columns {
        if !names.insert(rust_name(&col.name)) {
            return Err("Коллизия Rust-имён полей".into());
        }
    }
    let mut out = String::from("// @generated by minidb gen; edit the schema, not this file.\n");
    writeln!(out, "pub const VERSION: u32 = {};", schema.version)?;
    writeln!(out, "pub const TABLE: &str = {:?};", schema.name)?;
    writeln!(out, "pub const SCHEMA: &str = {:?};", schema.to_text())?;
    writeln!(
        out,
        "pub const LAYOUT: &[(usize, usize)] = &{:?};",
        layout
            .cols
            .iter()
            .map(|c| (c.offset, c.width))
            .collect::<Vec<_>>()
    )?;
    writeln!(
        out,
        "pub const COLUMNS: &[(&str, usize, u8)] = &{:?};",
        schema
            .columns
            .iter()
            .map(|c| Ok((c.name.as_str(), c.width()?, tag(c.data_type.kind))))
            .collect::<Result<Vec<_>>>()?
    )?;
    writeln!(
        out,
        "#[derive(Clone, Debug, Default, PartialEq)]\npub struct {name} {{"
    )?;
    let initial = schema.history()[&1];
    for (i, col) in schema.columns.iter().enumerate() {
        let ty = match col.data_type.kind {
            Kind::Null => return Err("Отложенный тип ещё не определён".into()),
            Kind::Int { .. } => "i64",
            Kind::Float { .. } => "f64",
            Kind::String { .. } => "::std::string::String",
        };
        let ty = if col.data_type.nullable || i >= initial {
            format!("::std::option::Option<{ty}>")
        } else {
            ty.into()
        };
        writeln!(out, "    pub {}: {ty},", rust_name(&col.name))?;
    }
    writeln!(out, "}}\nimpl {name} {{\n    pub const VERSION: u32 = VERSION;\n    pub const LAYOUT: &'static [(usize, usize)] = LAYOUT;")?;
    writeln!(out, "    pub fn check_schema_once(schema: &::minidb::Schema) -> ::minidb::Result<()> {{\n        ::minidb::codegen::check_schema_once(schema, TABLE, VERSION, COLUMNS)\n    }}")?;
    writeln!(out, "    pub fn from_row(row: ::minidb::Row<'_>) -> ::minidb::Result<Self> {{\n        ::minidb::codegen::check_reader(row, TABLE, VERSION, COLUMNS)?;\n        Self::decode_row(row)\n    }}")?;
    writeln!(out, "    pub fn scan(db: &mut ::minidb::Database, filter: &::minidb::Expr<'_>, mut visit: impl FnMut(Self) -> ::minidb::Result<()>) -> ::minidb::Result<usize> {{\n        Self::check_schema_once(db.schema(TABLE)?)?;\n        db.scan(TABLE, filter, |row| {{\n            ::minidb::codegen::check_record(row)?;\n            visit(Self::decode_row(row)?)\n        }})\n    }}")?;
    writeln!(out, "    fn decode_row(row: ::minidb::Row<'_>) -> ::minidb::Result<Self> {{\n        ::std::result::Result::Ok(Self {{")?;
    for (i, col) in schema.columns.iter().enumerate() {
        let field = rust_name(&col.name);
        let (variant, decode) = match col.data_type.kind {
            Kind::Null => return Err("Отложенный тип ещё не определён".into()),
            Kind::Int { .. } => ("Int", "value"),
            Kind::Float { .. } => ("Float", "value"),
            Kind::String { .. } => ("String", "value.to_owned()"),
        };
        let optional = col.data_type.nullable || i >= initial;
        let decoded = if optional {
            format!("::std::option::Option::Some({decode})")
        } else {
            decode.into()
        };
        writeln!(out, "            {field}: match row.at({i})? {{")?;
        writeln!(
            out,
            "                ::minidb::Value::{variant}(value) => {decoded},"
        )?;
        if optional {
            writeln!(
                out,
                "                ::minidb::Value::Null => ::std::option::Option::None,"
            )?;
        }
        writeln!(
            out,
            "                _ => return ::std::result::Result::Err({:?}.into()),\n            }},",
            format!("Неверный тип/NULL: {}.{}", schema.name, col.name)
        )?;
    }
    writeln!(out, "        }})\n    }}\n    pub fn to_values(&self) -> ::std::vec::Vec<::minidb::Value<'_>> {{\n        vec![")?;
    for (i, col) in schema.columns.iter().enumerate() {
        let field = rust_name(&col.name);
        let (variant, access) = match col.data_type.kind {
            Kind::Null => return Err("Отложенный тип ещё не определён".into()),
            Kind::Int { .. } => ("Int", ""),
            Kind::Float { .. } => ("Float", ""),
            Kind::String { .. } => ("String", ".as_str()"),
        };
        let expr = if col.data_type.nullable || i >= initial {
            let optional = if matches!(col.data_type.kind, Kind::String { .. }) {
                ".as_deref()"
            } else {
                ""
            };
            format!("self.{field}{optional}.map(::minidb::Value::{variant}).unwrap_or(::minidb::Value::Null)")
        } else {
            format!("::minidb::Value::{variant}(self.{field}{access})")
        };
        writeln!(out, "            {expr},")?;
    }
    writeln!(out, "        ]\n    }}")?;
    writeln!(out, "    pub fn insert(&self, db: &mut ::minidb::Database) -> ::minidb::Result<i64> {{\n        db.insert_versioned(TABLE, VERSION, &self.to_values())\n    }}")?;
    writeln!(out, "    pub fn update(&self, db: &mut ::minidb::Database, id: i64) -> ::minidb::Result<usize> {{\n        db.check_version(TABLE, VERSION)?;\n        let values = self.to_values();\n        let assignments: ::std::vec::Vec<_> = COLUMNS.iter().zip(values).enumerate().filter(|(index, _)| *index != {}).map(|(_, ((name, _, _), value))| (*name, value)).collect();\n        db.update(TABLE, &::minidb::Expr::Compare({:?}, ::minidb::Compare::Eq, ::minidb::Value::Int(id)), &assignments)\n    }}", schema.primary_key, schema.columns[schema.primary_key].name)?;
    if schema.validator.is_some() {
        writeln!(out, "    pub fn validator_adapter(row: ::minidb::Row<'_>) -> ::minidb::Result<()> {{\n        Self::from_row(row)?.validate()\n    }}")?;
    }
    writeln!(out, "}}")?;
    Ok(out)
}

/// Детерминированный tables.rs: модуль на каждую *.schema.sql (или прежнюю *.schema).
pub fn generate_dir(root: impl AsRef<Path>) -> Result<String> {
    let paths = crate::storage::schema_files(root.as_ref())?;
    let mut out = String::new();
    let mut modules = HashSet::new();
    for (name, path) in paths {
        let schema = Schema::from_text(&std::fs::read_to_string(&path)?)?;
        if name != schema.name {
            return Err("Имя файла схемы не совпадает с именем таблицы".into());
        }
        let module = rust_name(&schema.name);
        if !modules.insert(module.clone()) {
            return Err("Коллизия Rust-имён таблиц".into());
        }
        writeln!(out, "pub mod {module} {{\n{}\n}}", generate(&schema)?)?;
    }
    Ok(out)
}
